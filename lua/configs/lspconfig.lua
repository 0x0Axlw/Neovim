-- ============================================================================
-- OPTIONAL SERVER CUSTOMIZATION
-- ============================================================================

-- QML / Qt / Quickshell
--
-- This one is special because qmlls lives outside PATH on your machine.
-- ============================================================================

if vim.uv.fs_stat("/usr/lib/qt6/bin/qmlls") then
  vim.lsp.config("qmlls", {
    cmd = {
      "/usr/lib/qt6/bin/qmlls",
    },
  })

  vim.lsp.enable("qmlls")
end

-- ============================================================================
-- ENABLE AVAILABLE SERVERS
-- ============================================================================

for _, server in ipairs(servers) do
  if vim.fn.executable(server.executable) == 1 then
    vim.lsp.enable(server.name)
  end
end
